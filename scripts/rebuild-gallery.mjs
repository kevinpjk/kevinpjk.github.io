#!/usr/bin/env node
/**
 * rebuild-gallery.mjs
 * Scans public/assets/img/gallery/ folders and rebuilds src/data/gallery.yaml
 * Preserves existing location and date fields.
 *
 * Usage: node scripts/rebuild-gallery.mjs
 */

import fs from 'node:fs';
import path from 'node:path';
import { execSync } from 'node:child_process';
import yaml from 'js-yaml';

const GALLERY_DIR = path.resolve('public/assets/img/gallery');
const YAML_PATH = path.resolve('src/data/gallery.yaml');
const IMAGE_EXTS = new Set(['.jpg', '.jpeg', '.png', '.gif', '.webp', '.heic']);
const VIDEO_EXTS = new Set(['.mp4', '.mov', '.webm']);

// Load existing YAML to preserve location/date
let existing = [];
try {
  const raw = fs.readFileSync(YAML_PATH, 'utf-8');
  existing = yaml.load(raw) || [];
} catch { /* first run */ }
const existingMap = new Map(existing.map(e => [e.event, e]));

// Parse folder name into event info
function parseFolderName(folder) {
  // Handle patterns: chi2025, uist2024, seattle_summer2024
  const match = folder.match(/^([a-z_]+?)(\d{4})$/i);
  if (match) {
    const rawName = match[1].replace(/_/g, ' ').trim();
    const year = match[2];
    // Capitalize each word and uppercase known acronyms
    const acronyms = new Set(['chi', 'uist', 'cscw', 'iui', 'vis']);
    const event = rawName
      .split(' ')
      .map(w => acronyms.has(w.toLowerCase()) ? w.toUpperCase() : w.charAt(0).toUpperCase() + w.slice(1))
      .join(' ');
    return { event: `${event} ${year}`, year };
  }
  // Fallback: just capitalize
  return { event: folder, year: '' };
}

// Scan folders
const folders = fs.readdirSync(GALLERY_DIR)
  .filter(f => fs.statSync(path.join(GALLERY_DIR, f)).isDirectory())
  .sort();

const events = [];

for (const folder of folders) {
  const { event, year } = parseFolderName(folder);
  const prev = existingMap.get(event);

  const folderPath = path.join(GALLERY_DIR, folder);
  const files = fs.readdirSync(folderPath).sort();

  const photos = [];
  // Group HEIC+MP4 pairs as live photos
  const heicFiles = new Set();
  const mp4Files = new Set();
  const otherImages = [];

  for (const file of files) {
    const ext = path.extname(file).toLowerCase();
    const base = path.parse(file).name;
    if (IMAGE_EXTS.has(ext)) {
      if (ext === '.heic') {
        heicFiles.add(base);
      } else {
        otherImages.push(file);
      }
    } else if (VIDEO_EXTS.has(ext)) {
      mp4Files.add(base);
    }
  }

  // Live photos: HEIC files that have a matching MP4.
  // Convert HEIC → JPG on first sight (browsers can't render .heic in <img>).
  let photoIndex = 1;
  for (const base of heicFiles) {
    const heicPath = path.join(folderPath, `${base}.HEIC`);
    const jpgPath = path.join(folderPath, `${base}.jpg`);
    if (!fs.existsSync(jpgPath) && fs.existsSync(heicPath)) {
      try {
        execSync(`sips -s format jpeg "${heicPath}" --out "${jpgPath}"`, { stdio: 'ignore' });
      } catch (e) {
        console.warn(`Failed to convert ${heicPath} to jpg:`, e.message);
      }
    }

    const hasVideo = mp4Files.has(base);
    const photo = {
      src: `gallery/${folder}/${base}.jpg`,
      thumb: `gallery/${folder}/${base}.jpg`,
      caption: `${event} ${photoIndex}`,
    };
    if (hasVideo) {
      photo.video = `gallery/${folder}/${base}.MP4`;
      photo.type = 'live';
    }
    photos.push(photo);
    photoIndex++;
  }

  // Regular images
  for (const file of otherImages) {
    photos.push({
      src: `gallery/${folder}/${file}`,
      thumb: `gallery/${folder}/${file}`,
      caption: `${event} ${photoIndex}`,
    });
    photoIndex++;
  }

  events.push({
    event,
    location: prev?.location || 'TODO',
    date: prev?.date || (year ? `${year}-01` : 'TODO'),
    photos,
  });
}

// Sort by date descending
events.sort((a, b) => b.date.localeCompare(a.date));

// Write YAML
const header = `# =============================================================================
# gallery.yaml — Auto-generated by scripts/rebuild-gallery.mjs
# Run: node scripts/rebuild-gallery.mjs
# =============================================================================\n\n`;

const yamlStr = yaml.dump(events, {
  lineWidth: -1,
  quotingType: '"',
  forceQuotes: true,
});

fs.writeFileSync(YAML_PATH, header + yamlStr, 'utf-8');
console.log(`Gallery rebuilt: ${events.length} events, ${events.reduce((s, e) => s + e.photos.length, 0)} photos`);
